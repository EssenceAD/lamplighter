// Finds, for every night, how much shadow the built-in bot can just hold with a full set
// of windows, then sets each night a little under that (easy / easy / normal / hard).
// The bot never steers the beam by hand, so a careful player has room to do better.
// Writes src/tuning.js. Run: node tools/calibrate.mjs
import fs from 'node:fs';
import { Sim, Bot } from '../src/sim.js';
import { buildWorld } from '../src/world.js';
import { makeLevel, STAGES, CHAPTERS, UPGRADES } from '../src/levels.js';

const SHAPES = JSON.parse(fs.readFileSync(new URL('../assets/shapes.json', import.meta.url)));
function spend(save) {
  for (;;) {
    let best = null;
    for (const u of UPGRADES) { const l = save.up[u.id] || 0; if (l >= u.cost.length || (u.ch != null && u.ch > save.ch)) continue; if (!best || u.cost[l] < best.c) best = { u, c: u.cost[l] }; }
    if (!best || best.c > save.sparkles) return;
    save.sparkles -= best.c; save.up[best.u.id] = (save.up[best.u.id] || 0) + 1;
  }
}
function play(world, level, up, seed) {
  const sim = new Sim({ path: world.path, tower: world.tower, level, upgrades: up, seed }), bot = new Bot(sim);
  for (let i = 0; i < 30 * 400 && !sim.done; i++) { bot.step(1 / 30); sim.step(1 / 30); }
  return sim;
}
const EASE = [0.5, 0.62, 0.8, 0.95];
const save = { up: {}, sparkles: 0, ch: 0 }, tune = [];
for (let c = 0; c < CHAPTERS.length; c++) {
  save.ch = c; const world = buildWorld(SHAPES, c % 2 === 1);
  for (let s = 0; s < STAGES; s++) {
    const id = c * STAGES + s;
    globalThis.__TUNE = { [id]: 1 };
    const tier = makeLevel(c, s, world.slots).tier;
    const holds = m => { globalThis.__TUNE = { [id]: m }; const L = makeLevel(c, s, world.slots); return [3, 4].every(seed => play(world, L, save.up, seed).stars === 3); };
    let lo = 0.2, hi = 14;
    if (c === 0 && s < 3) { lo = 1; } else if (!holds(lo)) { hi = lo; } else { for (let i = 0; i < 10; i++) { const mid = Math.sqrt(lo * hi); if (holds(mid)) lo = mid; else hi = mid; } }
    const m = c === 0 && s < 3 ? 1 : +(lo * EASE[s % 4 === 3 ? 3 : tier]).toFixed(3);
    tune[id] = Math.max(0.15, m);
    globalThis.__TUNE = { [id]: tune[id] };
    const L = makeLevel(c, s, world.slots), res = play(world, L, save.up, 5);
    const n = L.waves.reduce((a, b) => a + b.n, 0);
    console.log(L.name, L.tierName, 'crit', lo.toFixed(2), 'tune', tune[id], 'spawns', n, res.phase, res.stars, JSON.stringify(save.up));
    save.sparkles += L.reward; spend(save);
  }
}
fs.writeFileSync(new URL('../src/tuning.js', import.meta.url), `// generated by tools/calibrate.mjs — per-night shadow budget multipliers\nexport const TUNE = ${JSON.stringify(tune)};\n`);
